import os
import shutil
import subprocess
import sys
from pathlib import Path
import fitz
import openpyxl

from . import pdf_engine

HAS_WIN32 = False
if sys.platform == "win32":
    try:
        import pythoncom
        import win32com.client as win32
        HAS_WIN32 = True
    except ImportError:
        HAS_WIN32 = False

XL_TYPE_PDF = 0
WD_FORMAT_XML_DOCUMENT = 16  # .docx
WD_EXPORT_FORMAT_PDF = 17    # .pdf
WD_ORIENT_LANDSCAPE = 1
WD_AUTOFIT_WINDOW = 2

COMPANY_ADDRESS = (
    "Claaps Global Enterprises Private Limited, Q3, 6th Floor, "
    "Cyber Towers, Hitech City, Madhapur, Hyderabad,Telangana 500082"
)


def _prune_blank_pages(pdf_path: Path):
    """Removes empty/phantom pages generated by print margins or overflow."""
    try:
        if not pdf_path.exists():
            return
        with open(pdf_path, "rb") as f_in:
            pdf_bytes = f_in.read()

        raw_pdf = fitz.open(stream=pdf_bytes, filetype="pdf")
        if raw_pdf.page_count > 1:
            clean_pdf = fitz.open()
            for p in raw_pdf:
                has_text = bool(p.get_text().strip())
                has_drawings = bool(p.get_drawings())
                has_images = bool(p.get_images())
                if has_text or has_drawings or has_images:
                    clean_pdf.insert_pdf(raw_pdf, from_page=p.number, to_page=p.number)
            if 0 < clean_pdf.page_count < raw_pdf.page_count:
                clean_pdf.save(str(pdf_path), incremental=False, deflate=True)
            clean_pdf.close()
        raw_pdf.close()
    except Exception:
        pass


def _convert_excel_via_libreoffice(input_excel: Path, output_docx: Path, output_pdf: Path) -> tuple[bool, str]:
    """Linux/Docker/LibreOffice conversion fallback for Excel files."""
    soffice_cmd = shutil.which("soffice") or shutil.which("libreoffice")
    if not soffice_cmd:
        return False, "LibreOffice (soffice) not found on system."

    # 1. Inject address using openpyxl if needed
    work_excel = input_excel
    temp_mod_excel = output_pdf.parent / f"mod_{input_excel.name}"
    try:
        wb = openpyxl.load_workbook(str(input_excel))
        ws = wb.active
        modified = False
        for r in range(1, 15):
            for c in range(1, 30):
                cell = ws.cell(r, c)
                val = str(cell.value or "")
                if (
                    "Name & Address of the company" in val
                    or "Name and Address of the company" in val
                    or "Name & Address of Establishment" in val
                ):
                    if "Claaps Global Enterprises" not in val:
                        cell.value = f"Name & Address of the company:\n{COMPANY_ADDRESS}"
                        modified = True
        if modified:
            wb.save(str(temp_mod_excel))
            work_excel = temp_mod_excel
        wb.close()
    except Exception:
        pass

    # 2. Run LibreOffice headless conversion to PDF
    try:
        out_dir = output_pdf.parent
        res = subprocess.run(
            [soffice_cmd, "--headless", "--convert-to", "pdf", "--outdir", str(out_dir), str(work_excel)],
            capture_output=True,
            text=True,
            timeout=90,
        )
        expected_pdf = out_dir / f"{work_excel.stem}.pdf"
        if expected_pdf.exists():
            if expected_pdf.resolve() != output_pdf.resolve():
                shutil.move(str(expected_pdf), str(output_pdf))
            # Also create a placeholder/copy for docx
            try:
                if not output_docx.exists():
                    import docx
                    d = docx.Document()
                    d.add_heading(f"Converted from {input_excel.name}", level=1)
                    d.save(str(output_docx))
            except Exception:
                pass
            return True, "OK"
        return False, f"LibreOffice conversion failed: {res.stderr or res.stdout}"
    except Exception as exc:
        return False, f"LibreOffice error: {exc}"
    finally:
        if temp_mod_excel.exists():
            try:
                temp_mod_excel.unlink()
            except Exception:
                pass


def convert_excel_to_word_to_pdf(
    input_excel: str,
    output_docx: str,
    output_pdf: str,
) -> tuple[bool, str]:
    """
    Complete pipeline for Excel files:
    1. Opens Excel and inspects headers (injecting company address into Form F top right).
    2. Trims empty trailing rows so documents don't spill unnecessary blank pages.
    3. Converts into Word (.docx) with Landscape orientation and auto-fit to window.
    4. For wide muster rolls (e.g. Form T with 30+ columns), exports directly to PDF
       to preserve the standard 2-page muster roll layout while saving the .docx copy.
    5. Exports Word to PDF (.pdf) and prunes blank pages.
    Falls back to headless LibreOffice on Linux/Render/Docker environments.
    """
    input_abs = Path(input_excel).resolve()
    docx_abs = Path(output_docx).resolve()
    pdf_abs = Path(output_pdf).resolve()
    docx_abs.parent.mkdir(parents=True, exist_ok=True)
    pdf_abs.parent.mkdir(parents=True, exist_ok=True)

    # 1. On Windows with Office, run native COM automation
    if HAS_WIN32:
        pythoncom.CoInitialize()
        excel = None
        wb = None
        word = None
        doc = None
        try:
            excel = win32.Dispatch("Excel.Application")
            excel.Visible = False
            excel.DisplayAlerts = False
            excel.ScreenUpdating = False

            wb = excel.Workbooks.Open(str(input_abs), ReadOnly=False, UpdateLinks=False)
            ws = wb.Sheets(1)

            # 1. Address injection if specified in template (e.g. Form F top right)
            is_form_t = False
            for r in range(1, 15):
                for c in range(1, 30):
                    try:
                        val = str(ws.Cells(r, c).Value or "")
                        if "FORM T" in val or "FORM-T" in val or "Muster Roll" in val:
                            is_form_t = True
                        if (
                            "Name & Address of the company" in val
                            or "Name and Address of the company" in val
                            or "Name & Address of Establishment" in val
                        ):
                            if "Claaps Global Enterprises" not in val:
                                ws.Cells(r, c).Value = f"Name & Address of the company:\n{COMPANY_ADDRESS}"
                                ws.Cells(r, c).WrapText = True
                    except Exception:
                        pass

            # 2. Trim empty rows/columns to prevent ghost pages
            used = ws.UsedRange
            last_row = 1
            for r in range(used.Rows.Count, 0, -1):
                has_val = False
                for c in range(1, min(used.Columns.Count + 1, 45)):
                    v = ws.Cells(r, c).Value
                    if v is not None and str(v).strip():
                        has_val = True
                        break
                if has_val:
                    last_row = r
                    break

            last_col = min(used.Columns.Count, 45)

            # 3. Check for multi-column muster rolls like Form T
            if is_form_t and last_col > 30:
                wb.ExportAsFixedFormat(XL_TYPE_PDF, str(pdf_abs))
                try:
                    word = win32.Dispatch("Word.Application")
                    word.Visible = False
                    word.DisplayAlerts = False
                    word.ScreenUpdating = False
                    copy_range = ws.Range(ws.Cells(1, 1), ws.Cells(last_row, last_col))
                    copy_range.Copy()
                    doc = word.Documents.Add()
                    doc.PageSetup.Orientation = WD_ORIENT_LANDSCAPE
                    word.Selection.PasteExcelTable(False, False, False)
                    doc.SaveAs2(str(docx_abs), WD_FORMAT_XML_DOCUMENT)
                except Exception:
                    pass
            else:
                # Standard conversion via Word (Form F, Equal Remuneration, etc.)
                copy_range = ws.Range(ws.Cells(1, 1), ws.Cells(last_row, last_col))
                copy_range.Copy()

                word = win32.Dispatch("Word.Application")
                word.Visible = False
                word.DisplayAlerts = False
                word.ScreenUpdating = False

                doc = word.Documents.Add()
                doc.PageSetup.Orientation = WD_ORIENT_LANDSCAPE
                doc.PageSetup.LeftMargin = 25
                doc.PageSetup.RightMargin = 25
                doc.PageSetup.TopMargin = 25
                doc.PageSetup.BottomMargin = 25

                word.Selection.PasteExcelTable(False, False, False)

                if doc.Tables.Count > 0:
                    for tbl in doc.Tables:
                        tbl.AutoFitBehavior(WD_AUTOFIT_WINDOW)

                doc.SaveAs2(str(docx_abs), WD_FORMAT_XML_DOCUMENT)
                doc.ExportAsFixedFormat(str(pdf_abs), WD_EXPORT_FORMAT_PDF)

            _prune_blank_pages(pdf_abs)
            return True, "OK"
        except Exception:
            pass  # Fall back to LibreOffice
        finally:
            try:
                if doc is not None:
                    doc.Close(False)
            except Exception:
                pass
            try:
                if word is not None:
                    word.Quit()
            except Exception:
                pass
            try:
                if wb is not None:
                    wb.Close(False)
            except Exception:
                pass
            try:
                if excel is not None:
                    excel.Quit()
            except Exception:
                pass
            pythoncom.CoUninitialize()

    # 2. LibreOffice headless fallback (Linux / Docker on Render)
    ok_lo, msg_lo = _convert_excel_via_libreoffice(input_abs, docx_abs, pdf_abs)
    if ok_lo:
        _prune_blank_pages(pdf_abs)
        return True, "OK"

    return False, f"Conversion failed: {msg_lo}"


def convert_excel_to_pdf(input_path: str, output_path: str) -> tuple[bool, str]:
    """Compatibility wrapper that runs the Excel -> Word -> PDF pipeline."""
    docx_path = str(Path(output_path).with_suffix(".docx"))
    return convert_excel_to_word_to_pdf(input_path, docx_path, output_path)


def get_or_create_preview_pdf(excel_path: str) -> str | None:
    """Returns a cached PDF path for previewing the Excel document in the web UI."""
    preview_pdf = Path(excel_path).with_suffix(".preview.pdf")
    if preview_pdf.exists() and preview_pdf.stat().st_mtime >= Path(excel_path).stat().st_mtime:
        return str(preview_pdf)

    preview_docx = Path(excel_path).with_suffix(".preview.docx")
    ok, msg = convert_excel_to_word_to_pdf(excel_path, str(preview_docx), str(preview_pdf))
    if ok and preview_pdf.exists():
        return str(preview_pdf)
    return None


def get_excel_page_count(excel_path: str) -> int:
    pdf_path = get_or_create_preview_pdf(excel_path)
    if pdf_path and Path(pdf_path).exists():
        return pdf_engine.get_page_count(pdf_path)
    return 1


def process_excel(
    input_path: str,
    output_pdf_path: str,
    output_xlsx_path: str | None,
    target_page: str,
    signature: dict | None,
    stamp: dict | None,
    new_date: str | None,
    date_pattern: str | None,
    placement_mode: str = "hybrid",
    keywords: list[str] | None = None,
) -> tuple[bool, str, dict]:
    """
    1. Converts Excel to Word (.docx) and then to PDF (.pdf).
    2. Automatically populates company name and address in statutory forms.
    3. Prunes empty blank pages.
    4. Stamps CTO digital signature, company seal stamp, and date.
    5. Saves the final stamped PDF as output_pdf_path, and saves the Word (.docx) document.
    """
    meta: dict = {"detected_page": None, "detected_text": None, "is_fallback": 0}

    output_pdf = Path(output_pdf_path)
    output_dir = output_pdf.parent
    base_stem = output_pdf.stem
    intermediate_docx = str(output_dir / f"{base_stem}.docx")
    intermediate_pdf = str(output_dir / f"{base_stem}.temp.pdf")

    # 1. Convert Excel -> Word -> intermediate PDF
    ok_conv, msg_conv = convert_excel_to_word_to_pdf(input_path, intermediate_docx, intermediate_pdf)
    if not ok_conv or not Path(intermediate_pdf).exists():
        return False, f"Failed converting Excel to Word/PDF: {msg_conv}", meta

    try:
        # 2. Process and stamp the intermediate PDF
        ok, msg, meta = pdf_engine.process_pdf(
            input_path=intermediate_pdf,
            output_path=output_pdf_path,
            target_page=target_page,
            signature=signature,
            stamp=stamp,
            new_date=new_date,
            date_pattern=date_pattern,
            placement_mode=placement_mode,
            keywords=keywords,
        )

        # 3. If output_xlsx_path is requested, also copy the original xlsx
        if output_xlsx_path and Path(input_path).exists():
            try:
                shutil.copy2(input_path, output_xlsx_path)
            except Exception:
                pass

        return ok, msg, meta
    finally:
        # Clean up temporary intermediate PDF file
        try:
            if Path(intermediate_pdf).exists():
                Path(intermediate_pdf).unlink()
        except Exception:
            pass
